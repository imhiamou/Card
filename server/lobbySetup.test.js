const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");

test("Create Lobby opens setup and confirms before a room is created", () => {
  const index = fs.readFileSync(path.join(__dirname, "../index.js"), "utf8");
  const html = fs.readFileSync(path.join(__dirname, "../index.html"), "utf8");
  const mobile = fs.readFileSync(path.join(__dirname, "../assets/mobile-app.js"), "utf8");
  assert.match(html, /id="lobbyPlay"/);
  assert.match(html, /id="lobbyUpdates"/);
  assert.match(html, />Play</);
  assert.match(html, />Updates</);
  assert.match(html, /id="lobbySetup"/);
  assert.match(html, /id="lobbySetupConfirm"/);
  assert.match(html, /id="lobbySetupCancel"/);
  const play = html.slice(html.indexOf('id="lobbyPlay"'), html.indexOf('id="lobbyUpdates"'));
  assert.equal(play.includes('id="gameSelect"'), false);
  assert.equal(play.includes("appGameGrid"), false);
  assert.match(play, /id="playerName"/);
  assert.match(play, /id="createCode"/);
  assert.match(play, /id="roomCode"/);
  const setup = html.slice(html.indexOf('id="lobbySetup"'), html.indexOf('id="placementScreen"'));
  assert.match(setup, /id="gameSelect"/);
  assert.match(setup, /id="dominoMaxPlayers"/);
  assert.match(setup, /id="dominoTeamSelect"/);
  assert.match(setup, /id="botFillCheck"/);
  assert.match(setup, /id="unoMaxPlayers"/);
  assert.match(html, /id="gamewebCheckUpdate"/);
  const createAt = index.indexOf('document.getElementById("createBtn").onclick');
  const createFn = index.slice(createAt, createAt + 160);
  assert.match(createFn, /openLobbySetup\(\)/);
  assert.doesNotMatch(createFn, /submitCreateLobby\(\)/);
  assert.match(index, /lobbySetupCancel[\s\S]{0,120}closeLobbySetup/);
  const submitAt = index.indexOf("function submitCreateLobby");
  const submit = index.slice(submitAt, submitAt + 1800);
  assert.match(submit, /setLobbySetupError\(/);
  assert.match(submit, /socket\.emit\("createLobby"/);
  assert.match(submit, /payload\.maxPlayers/);
  assert.match(submit, /payload\.team/);
  assert.match(submit, /payload\.fillBots/);
  assert.ok(submit.indexOf("setLobbySetupError(") < submit.indexOf('socket.emit("createLobby"'));
  assert.match(index, /socket\.emit\("joinLobby"/);
  assert.equal(index.includes('data-app-tab="room"'), false);
  assert.match(mobile, /\["play", "Play"\], \["updates", "Updates"\]/);
  assert.doesNotMatch(mobile, /"setup"|"room"/);
});

test("the lobby Updates button reuses the Android updater", () => {
  const updater = fs.readFileSync(path.join(__dirname, "../assets/android-update.js"), "utf8");
  assert.match(updater, /gamewebCheckUpdate/);
  assert.match(updater, /Checking…/);
  assert.match(updater, /downloadAndInstall/);
  assert.doesNotMatch(updater, /api\.github\.com\/repos\/imhiamou\/Card\/releases\/latest/);
});
